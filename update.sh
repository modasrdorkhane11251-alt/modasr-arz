#!/usr/bin/env bash

# ==============================================================================
# 🔄 اسکریپت به‌روزرسانی خودکار ربات از گیت‌هاب (Update Script)
# ==============================================================================

set -e

GREEN='\033[0;32m'
CYAN='\033[0;36m'
BOLD='\033[1m'
NC='\033[0m'

echo -e "${CYAN}${BOLD}🔄 در حال دریافت آخرین آپدیت‌ها از مخزن گیت‌هاب...${NC}"
git pull || true

echo -e "${CYAN}📥 در حال بررسی و نصب پکیج‌های جدید...${NC}"
npm install

echo -e "${CYAN}🔨 در حال بیلد مجدد پروژه...${NC}"
npm run build

echo -e "${CYAN}🚀 در حال راه‌اندازی مجدد سرویس با PM2...${NC}"
pm2 restart modasr-bot

echo -e "\n${GREEN}${BOLD}✔ به‌روزرسانی پروژه با موفقیت انجام شد و ربات در حال اجرا است!${NC}\n"
pm2 status
